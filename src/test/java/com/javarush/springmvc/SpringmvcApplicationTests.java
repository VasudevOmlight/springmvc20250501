package com.javarush.springmvc;

import org.junit.jupiter.api.DisplayName; // Анотація для надання описового імені тесту
import org.junit.jupiter.api.Test;       // Основна анотація для позначення тестового методу в JUnit 5
import org.springframework.boot.test.context.SpringBootTest; // Основна анотація для інтеграційних тестів Spring Boot

// Стандартний інтеграційний тест, що генерується Spring Boot Initializr.
// Цей клас перевіряє, чи може контекст програми Spring Boot
// бути успішно завантажений без помилок.

@SpringBootTest // Ключова анотація для інтеграційного тестування Spring Boot.
        // Вона завантажує повний контекст програми (ApplicationContext),
        // включаючи всі конфігурації, біни (контролери, сервіси, репозиторії тощо),
        // та намагається налаштувати всі компоненти, як при реальному запуску програми.
class SpringmvcApplicationTests {

    @Test // Позначає цей метод як тестовий кейс JUnit 5
    @DisplayName("Перевірка успішного завантаження контексту програми")
    void contextLoads() {
        // Тіло тесту порожнє. Перевірка відбувається під час ініціалізації тесту
        // завдяки анотації @SpringBootTest. Якщо контекст не завантажиться,
        // тест завершиться з помилкою ще до виконання цього методу.
        System.out.println("Контекст програми успішно завантажено!");
    }
}
